const series = data.series.find(s => s.id === 'the-life-of-prophet-muhammad');
if (!series) {
  console.error('Series not found');
  process.exit(1);
}

// Add publication dates to episodes
let count = 0;
series.episodes.forEach(ep => {
  const match = ep.title.match(/^\[(\d+)\]/);
  if (match) {
    const epNum = parseInt(match[1]);
    if (pubDates[epNum]) {
      ep.published_date = pubDates[epNum];
      count++;
    }
  }
});

console.log(`Added publication dates to ${count} episodes`);

// Write back with proper YAML formatting
const output = yaml.dump(data, {
  lineWidth: -1,
  noRefs: true,
  quotingType: '"',
  forceQuotes: false,
});
fs.writeFileSync(yamlPath, output);
console.log('Done');
